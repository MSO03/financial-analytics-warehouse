CREATE DATABASE IF NOT EXISTS FINANCIAL_ANALYTICS;

USE DATABASE FINANCIAL_ANALYTICS;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS MARTS;

USE SCHEMA RAW;

CREATE TABLE raw.prices (
    trade_date DATE,
    ticker STRING,
    open FLOAT,
    high FLOAT,
    low FLOAT,
    close FLOAT,
    volume NUMBER
);
